"""Golden-file invariants: docs/test-spec-invariants.md B (policy) and E
(backtest). The committed fixtures in tests/golden/ are owner-controlled and
are never regenerated by tests; the chain well_calibrated/7 (synth, calibrate,
plan with the emitted costs, backtest with --history = the same batch, seed
7) is rebuilt and compared against them."""

from __future__ import annotations

from typing import Any

import pytest

from tests.support import GOLDEN_DIR, load_json
from triage.artifacts import content_hash


@pytest.fixture(scope="module")
def regenerated(chain: Any) -> Any:
    return chain("well_calibrated", 7)


@pytest.mark.parametrize("name", ["policy", "backtest"])
def test_regenerated_matches_fixture(regenerated: Any, name: str) -> None:
    """Spec B / E: the regenerated artifact equals the committed fixture after
    deleting created_at in both (full dict equality, not just hash equality)."""
    regenerated_artifact = regenerated.load(name)
    fixture = load_json(GOLDEN_DIR / f"{name}.json")
    regenerated_artifact.pop("created_at", None)
    fixture.pop("created_at", None)
    assert regenerated_artifact == fixture


@pytest.mark.parametrize("name", ["policy", "backtest"])
def test_fixture_hash_self_consistent(name: str) -> None:
    """Spec B / E: the fixture's own policy_hash / backtest_hash matches
    content_hash of the fixture content (self-consistency of the committed
    artifact)."""
    fixture: dict[str, Any] = load_json(GOLDEN_DIR / f"{name}.json")
    assert fixture[f"{name}_hash"] == content_hash(fixture)
